"""Per-compound markdown evidence cards.

For each top-ranked compound, gather its ranking, docking, efficiency and ADMET
numbers from the run's CSVs into one self-contained markdown card. Each card is
a hypothesis-generating summary, carries the method caveats, and makes no claim
of measured activity. It is a read-only re-presentation of existing outputs.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import pandas as pd

from ..config import Config
from ..logging_utils import get_logger

__all__ = ["write_dossiers"]

log = get_logger("report.dossier")


def _safe(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_-]+", "_", name).strip("_") or "compound"


def _g(row: pd.Series | None, key: str, default: str = "-") -> Any:
    if row is None or key not in row:
        return default
    value = row[key]
    return default if value is None or value == "" else value


def _render_card(cfg: Config, r: pd.Series, a: pd.Series | None, d: pd.Series | None) -> str:
    lines: list[str] = [
        f"# {_g(r, 'name', '(unknown)')} — vs {_g(r, 'target_name', _g(r, 'receptor_id'))}",
        "",
        f"*Rank {_g(r, 'rank', '?')} for receptor `{_g(r, 'receptor_id')}`. An npcadd "
        "evidence card: a hypothesis-generating summary, not a claim of activity.*",
        "",
        "## Identity",
        f"- ligand_id: `{_g(r, 'ligand_id')}`",
        f"- compound class: {_g(r, 'compound_class')}",
    ]
    if a is not None:
        lines.append(f"- SMILES: `{_g(a, 'smiles')}`")
        npl = _g(a, "np_likeness_score", "")
        if npl != "":
            lines.append(f"- NP-likeness: {npl} ({_g(a, 'np_likeness_class')})")
    lines += [
        f"- GC-MS area %: {_g(r, 'area_percent')}",
        "",
        "## Docking (ranking/triage only — a Vina score is not an affinity)",
        f"- best affinity: {_g(r, 'best_affinity_kcal_mol')} kcal/mol",
    ]
    if d is not None:
        placed = (
            "inside the search box"
            if str(_g(d, "placement_ok")) == "True"
            else str(_g(d, "placement_note"))
        )
        lines += [
            f"- pose consensus: mean of the best poses = "
            f"{_g(d, 'mean_top_affinity_kcal_mol')} kcal/mol; spread "
            f"{_g(d, 'affinity_spread_kcal_mol')} kcal/mol over "
            f"{_g(d, 'n_poses_returned')} returned poses",
            f"- top-2 pose RMSD: {_g(d, 'top2_pose_rmsd_a')} A",
            f"- placement: {placed}",
            f"- z vs null: {_g(r, 'z_score_vs_null')}; empirical p: {_g(r, 'empirical_p_vs_null')}",
        ]
        contacts = _g(d, "contact_residues", "")
        if str(contacts).strip():
            lines.append(f"- contact residues: {contacts}")
    lines += [
        "",
        "## Efficiency metrics (the basis for ranking)",
        f"- ligand efficiency (LE): {_g(r, 'ligand_efficiency_kcal_mol_per_ha')} kcal/mol/HA",
        f"- LLE: {_g(r, 'lipophilic_efficiency_lle')}; LELP: {_g(r, 'lelp')}; "
        f"fit quality: {_g(r, 'fit_quality')}",
        f"- BEI: {_g(r, 'binding_efficiency_index_bei')}; SEI: "
        f"{_g(r, 'surface_efficiency_index_sei')}; SILE: {_g(r, 'size_independent_le_sile')}",
        f"- multi-criteria score: {_g(r, 'multi_criteria_score')}",
        "",
        "## ADMET (offline; not a substitute for assay)",
        f"- rule pass rate: {_g(r, 'admet_pass_rate')}",
    ]
    if a is not None:
        lines.append(
            f"- MW {_g(a, 'mw')}, cLogP {_g(a, 'clogp')}, TPSA {_g(a, 'tpsa')}, "
            f"HBD {_g(a, 'hbd')}, HBA {_g(a, 'hba')}, QED {_g(a, 'qed')}"
        )
    flags = str(_g(r, "flags", "")).strip()
    if flags:
        lines += ["", "## Flags and caveats"]
        lines += [f"- {part.strip()}" for part in flags.split(";") if part.strip()]
    lines += [
        "",
        "---",
        f"*Generated by npcadd for study `{cfg.study}`. Every number above is "
        "computational and conditional on the method limits in LIMITATIONS.md.*",
        "",
    ]
    return "\n".join(lines)


def write_dossiers(cfg: Config, out_dir: Path, reports_dir: Path, top_n: int = 5) -> list[Path]:
    """Write one markdown card per top-``top_n`` ranked compound-target pair.

    Raises:
        FileNotFoundError: if the run has not been ranked yet.
    """
    ranked_path = out_dir / "ranked_compounds.csv"
    if not ranked_path.is_file():
        raise FileNotFoundError(
            f"No ranked_compounds.csv in {out_dir}; run 'npcadd rank' (or run-all) first."
        )
    ranked = pd.read_csv(ranked_path, keep_default_na=False)

    def _load(name: str) -> pd.DataFrame:
        path = out_dir / name
        return pd.read_csv(path, keep_default_na=False) if path.is_file() else pd.DataFrame()

    admet = _load("admet_results.csv")
    dock = _load("docking_results.csv")
    admet_by = (
        {str(row["ligand_id"]): row for _, row in admet.iterrows()} if not admet.empty else {}
    )
    dock_by = (
        {(str(row["ligand_id"]), str(row["receptor_id"])): row for _, row in dock.iterrows()}
        if not dock.empty
        else {}
    )

    top = ranked[ranked["rank"] <= top_n] if "rank" in ranked.columns else ranked.head(top_n)
    dossier_dir = reports_dir / "dossiers"
    dossier_dir.mkdir(parents=True, exist_ok=True)

    paths: list[Path] = []
    for _, row in top.iterrows():
        lid, rid = str(row.get("ligand_id", "")), str(row.get("receptor_id", ""))
        card = _render_card(cfg, row, admet_by.get(lid), dock_by.get((lid, rid)))
        try:
            rank_int = int(row.get("rank", 0))
        except (TypeError, ValueError):
            rank_int = 0
        path = (
            dossier_dir
            / f"{rank_int:02d}_{_safe(str(row.get('name', 'compound')))}_{_safe(rid)}.md"
        )
        path.write_text(card, encoding="utf-8")
        paths.append(path)

    log.info("Wrote dossier cards", extra={"n": len(paths), "dir": dossier_dir.as_posix()})
    return paths
